/** Full translation object for an English/German name pair. */
export function tr(en: string, de: string): Name {
    const rest = DICT[en];
    const out: Name = { en, de };
    for (const l of LANGS) {
        out[l] = rest?.[l] ?? en;
    }
    return out;
}

/** "Slot 1 color" in every language. */
export function slotName(nr: string, part: Name): Name {
    const slot = tr('Slot', 'Slot');
    const out: Name = { en: `Slot ${nr} ${part.en}`, de: `Slot ${nr} ${part.de}` };
    for (const l of LANGS) {
        out[l] = `${slot[l]} ${nr} ${part[l]}`;
    }
    return out;
}

/** Channel name "Slot 1" in every language. */
export function slotChannel(nr: string): Name {
    const slot = tr('Slot', 'Slot');
    const out: Name = { en: `Slot ${nr}`, de: `Slot ${nr}` };
    for (const l of LANGS) {
        out[l] = `${slot[l]} ${nr}`;
    }
    return out;
}

/** English texts without a translation, for the test. */
export function missing(texts: string[]): string[] {
    return texts.filter(x => !DICT[x]);
}
